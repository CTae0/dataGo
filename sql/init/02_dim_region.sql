-- 실거래가 API에 넣을 코드를 계약년월로 고르는 함수.
-- 2026-10-21 확인(molit_rent.py probe, 춘천 2011-01 ~ 2026-08, 4개 유형):
--   국토부 API는 과거 거래까지 모두 새 코드(51xxx)로 응답하고, 옛 코드(42xxx)는 항상 0건이다.
--   그래서 기간과 상관없이 region_code를 돌려준다. 옛 코드는 다른 원천(옛 파일 등) 연결용으로만 남긴다.
--   API가 바뀌면 이 함수만 고치면 된다 (수집기는 --codes auto일 때 이 함수를 쓴다).
CREATE OR REPLACE FUNCTION dim.lawd_cd_for(p_region_code char(5), p_deal_ym char(6))
RETURNS char(5) LANGUAGE sql STABLE AS $$
    SELECT region_code FROM dim.region WHERE region_code = p_region_code
$$;
